//! Dump the DualShock 4 USB identity and HID report descriptor.
//!
//! ```sh
//! cargo run -p livvirtualhid --example dump_ds4 > ds4_usb.h
//! ```
//!
//! The output is a C header the RP2040 firmware can include directly.

use livvirtualhid::{dualshock4_descriptor, dualshock4_info, Framing, GamepadState, ALL_BUTTONS};

fn main() {
    let info = dualshock4_info(Framing::Usb);
    let descriptor = dualshock4_descriptor(Framing::Usb);
    let sample = livvirtualhid::pack_dualshock4_report(Framing::Usb, &GamepadState::with_all_buttons());
    let neutral = livvirtualhid::pack_dualshock4_report(Framing::Usb, &GamepadState::neutral());

    println!("/* Generated by `cargo run -p livvirtualhid --example dump_ds4`.");
    println!(" * DualShock 4 USB identity + HID report descriptor, data taken from");
    println!(" * libvirtualhid (MIT). Embed in RP2040 TinyUSB firmware. */");
    println!("#pragma once");
    println!();
    println!("/* identity */");
    println!("#define DS4_VENDOR_ID      0x{:04X}", info.vendor_id);
    println!("#define DS4_PRODUCT_ID     0x{:04X}", info.product_id);
    println!("#define DS4_VERSION        0x{:04X}", info.version);
    println!("#define DS4_REPORT_ID      0x{:02X}", info.report_id);
    println!("#define DS4_INPUT_REPORT_SIZE  {}u", info.input_report_size);
    println!("#define DS4_OUTPUT_REPORT_SIZE {}u", info.output_report_size);
    println!("/* vendor id 0x{:04X} = Sony, product 0x{:04X} */", info.vendor_id, info.product_id);
    println!();
    println!("/* {} bytes, all-pressed sample report: {} */",
        sample.len(),
        sample.iter().map(|b| format!("{b:02x}")).collect::<Vec<_>>().join(" "));
    println!();
    println!("static const unsigned char kDs4ReportDescriptor[{}] = {{", descriptor.len());
    for chunk in descriptor.chunks(12) {
        let line = chunk.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ");
        println!("    {line},");
    }
    println!("}};");
    println!();
    println!("static const unsigned kDs4ReportDescriptorLength = {};", descriptor.len());
    println!();
    println!("/* neutral payload: packed report without the leading report id byte */");
    println!("static const unsigned char kDs4NeutralPayload[{}] = {{", neutral.len() - 1);
    for chunk in neutral[1..].chunks(12) {
        let line = chunk.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ");
        println!("    {line},");
    }
    println!("}};");
    println!();
    println!("/* all-buttons payload: packed report without the leading report id byte */");
    println!("static const unsigned char kDs4AllButtonsPayload[{}] = {{", sample.len() - 1);
    for chunk in sample[1..].chunks(12) {
        let line = chunk.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ");
        println!("    {line},");
    }
    println!("}};");
    println!();
    println!("/* logical button bit -> index (matches livvirtualhid GamepadButton) */");
    println!("#define DS4_BUTTON_MASK 0x{:06X}u", livvirtualhid::all_buttons_mask());
    for (index, button) in ALL_BUTTONS.iter().enumerate() {
        println!("#define DS4_BIT_{:<14} {}u  /* {} */", button.name().to_uppercase(), index, button.name());
    }
}
